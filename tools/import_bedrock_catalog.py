#!/usr/bin/env python3
"""Rebuild the offline recipe catalog from pinned, publicly available Bedrock data."""

import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
BEDROCK_REV = "bdb44a48fb6beffb6e9f6864f06d2232eb62b6a3"  # Bedrock 1.26.30
GEYSER_REV = "81700ab543c1f4e9f9041f58dac4154ecb0d0c8b"  # Java 26.3 mappings
SAMPLES_REV = "15701fa9c13923f12662984c32c124327e40e3d3"
CATEGORIES = ("construction", "equipment", "items", "nature")


def download(repository, revision, path):
    url = f"https://raw.githubusercontent.com/{repository}/{revision}/{path}"
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8-sig")


def generate():
    mappings = json.loads(download("GeyserMC/mappings", GEYSER_REV, "items.json"))
    reverse = {}
    by_name = {}
    for java_id, mapping in mappings.items():
        key = (mapping["bedrock_identifier"], mapping.get("bedrock_data", 0))
        reverse.setdefault(key, []).append(java_id)
        by_name.setdefault(mapping["bedrock_identifier"], []).append(java_id)

    language = download("Mojang/bedrock-samples", SAMPLES_REV, "resource_pack/texts/en_US.lang")
    labels = {}
    for line in language.splitlines():
        if line.startswith("itemGroup.name.") and "=" in line:
            key, value = line.split("=", 1)
            labels[key] = value.split("\t", 1)[0].strip()

    lines = [
        "# Generated by tools/import_bedrock_catalog.py. Do not hand-edit.",
        f"# BedrockData {BEDROCK_REV}; Geyser mappings {GEYSER_REV}; Bedrock labels {SAMPLES_REV}",
        "# category<TAB>group identifier (or -)<TAB>group label (or -)<TAB>Java item identifier",
    ]
    seen = set()
    skipped = set()
    for category in CATEGORIES:
        data = json.loads(download("pmmp/BedrockData", BEDROCK_REV, f"creative/{category}.json"))
        for section in data:
            group = section.get("group_name", "")
            for item in section["items"]:
                if isinstance(item, str):
                    name, meta = item, 0
                else:
                    name, meta = item["name"], item.get("meta", 0)
                java_ids = reverse.get((name, meta), [])
                # Flattened Bedrock block IDs can retain an old nonzero data value in
                # protocol mappings even though the creative catalog omits that value.
                if not java_ids and len(by_name.get(name, [])) == 1:
                    java_ids = by_name[name]
                if not java_ids:
                    skipped.add((name, meta))  # Education/Bedrock-only items have no Java recipe.
                for java_id in java_ids:
                    if java_id in seen:
                        continue
                    seen.add(java_id)
                    label = labels[group] if group else "-"
                    lines.append("\t".join((category, group or "-", label, java_id)))

    if len(seen) < 1000:
        raise RuntimeError("Unexpectedly small catalog; check upstream formats before updating.")
    target = ROOT / "src/main/resources/bedrock_recipe_book/catalog.tsv"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    licenses = target.parent / "licenses"
    licenses.mkdir(exist_ok=True)
    for repository, revision, source_license, filename in (
        ("pmmp/BedrockData", BEDROCK_REV, "LICENSE", "BedrockData-CC0.txt"),
        ("GeyserMC/mappings", GEYSER_REV, "LICENSE", "GeyserMappings-MIT.txt"),
        ("Mojang/bedrock-samples", SAMPLES_REV, "LICENSE.md", "BedrockSamples-license.txt"),
    ):
        (licenses / filename).write_text(download(repository, revision, source_license), encoding="utf-8")
    print(f"Generated {len(seen)} translated catalog items; omitted {len(skipped)} unmapped Bedrock-only variants.")


if __name__ == "__main__":
    generate()
